"""Write <build>/_blend_tables.py: PRED_TAB from a v18 PEl fit, BAND/WIDTH from v17. usage: make_tables18.py BUILD_DIR PKL KEY"""
import sys, os, pickle, importlib.util, numpy as np
sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("tb17", os.path.join(HERE, "..", "..", "submissions", "v17", "_blend_tables.py"))
TB = importlib.util.module_from_spec(spec); spec.loader.exec_module(TB)
build, pkl, key = sys.argv[1:4]
P = pickle.load(open(os.path.join(HERE, pkl), "rb"))[key]
B = np.array(TB.BAND_TAB) if len(sys.argv) < 5 else pickle.load(open(os.path.join(HERE, sys.argv[4]), "rb"))[sys.argv[5]]
W = np.array(TB.WIDTH_TAB) if len(sys.argv) < 7 else pickle.load(open(os.path.join(HERE, sys.argv[4]), "rb"))[sys.argv[6]]
assert P.shape == (20, 2, 6, 2) and B.shape == (20, 2, 6, 2) and W.shape == (4, 2, 10)
with open(os.path.join(build, "_blend_tables.py"), "w") as f:
    f.write(f'"""Generated by experiments/v18_refits/make_tables18.py {" ".join(sys.argv[1:])} (fit on SELECT).\n'
            'PRED_TAB: UNCONSTRAINED LS (lead 20, channel 2, sigma_local within-call sextile 6, [alpha on P-Em, beta on El-Em]).\n'
            'BAND_TAB / WIDTH_TAB as documented in experiments/estimator_blend/make_tables.py."""\n')
    f.write(f"PRED_TAB = {np.round(P, 6).tolist()!r}\n")
    f.write(f"BAND_TAB = {np.round(B, 6).tolist()!r}\n")
    f.write(f"WIDTH_TAB = {np.round(W, 7).tolist()!r}\n")
    f.write("BAND_G = 1.0\nBAND_MODE = 'tab'\n")
print("wrote", build, "pred range", P.min(), P.max())
