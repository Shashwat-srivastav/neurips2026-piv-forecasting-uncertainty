"""Write <build>/_blend_tables.py from per-window refit tables. usage: make_tables_pw.py PKL KEY BUILD_DIR"""
import sys, pickle, numpy as np, os
pkl, key, build = sys.argv[1:4]
pt, bt, H = pickle.load(open(pkl, "rb"))[key]
k = pt.shape[-1]
out = os.path.join(build, "_blend_tables.py")
with open(out, "w") as f:
    f.write(f'"""Generated by experiments/per_window_rebuild/make_tables_pw.py {pkl} {key} (fit on SELECT with PER-WINDOW rank bins).\n'
            f'PRED_TAB/BAND_TAB: (lead 20, channel 2, sigma_local PER-WINDOW sextile 6, {k} weights: alpha on P-Em, beta on El-Em'
            f'{", gamma on L-Em" if k == 3 else ""}).\n'
            'WIDTH_TAB: (lead group 4, channel 2, p1 PER-WINDOW decile 10) half-widths."""\n')
    f.write(f"PRED_TAB = {np.round(pt, 6).tolist()!r}\n")
    f.write(f"BAND_TAB = {np.round(bt, 6).tolist()!r}\n")
    f.write(f"WIDTH_TAB = {np.round(H, 7).tolist()!r}\n")
    f.write("BAND_G = 1.0\nBAND_MODE = 'tab'\n")
print("wrote", out, pt.shape, bt.shape, H.shape)
