"""Write submissions/v17/_blend_tables.py.
usage: make_tables.py PRED_FIT BAND_FIT [WIDTH_KEY]   e.g.  A AB  |  A AB AT,BT
PRED from tabs_pred.pkl ('both','sl',6,PRED_FIT); BAND centre from tabs_band_g1.pkl[BAND_FIT] (g=1);
WIDTH (optional) from tabs_width.pkl HW[(k1,k2)] -> p1-rank x lead-group half-width table, else v8 widths."""
import sys, pickle, numpy as np, os
P = pickle.load(open("tabs_pred.pkl", "rb"))[("both", "sl", 6, sys.argv[1])]
B = pickle.load(open("tabs_band_g1.pkl", "rb"))[sys.argv[2]]
W = None
if len(sys.argv) > 3:
    W = pickle.load(open("tabs_width.pkl", "rb"))["HW"][tuple(sys.argv[3].split(","))]
out = os.path.join("..", "..", "submissions", "v17", "_blend_tables.py")
with open(out, "w") as f:
    f.write(f'"""Generated by experiments/estimator_blend/make_tables.py {" ".join(sys.argv[1:])} (fit on SELECT).\n'
            'PRED_TAB/BAND_TAB: (lead 20, channel 2, sigma_local within-call sextile 6, [alpha on P-Em, beta on El-Em]).\n'
            'WIDTH_TAB: None (v8 widths) or (lead group 4, channel 2, p1 within-call decile 10) half-widths."""\n')
    f.write(f"PRED_TAB = {np.round(P, 6).tolist()!r}\n")
    f.write(f"BAND_TAB = {np.round(B, 6).tolist()!r}\n")
    f.write(f"WIDTH_TAB = {None if W is None else np.round(W, 7).tolist()!r}\n")
    f.write("BAND_G = 1.0\nBAND_MODE = 'tab'\n")
print("wrote", out, "width", None if W is None else W.shape)
